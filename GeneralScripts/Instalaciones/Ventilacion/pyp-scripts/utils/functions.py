                    # ──────────────────────────────────────────────────────────
                    # CASO 1 – MANGUITO
                    # ──────────────────────────────────────────────────────────
                    if tipo_str == "manguito":
                        segment_brep = None
                        if e == 0:
                            _, vp = brep.GetVertices()
                            if vp:
                                cx = sum(v.X for v in vp) / len(vp)
